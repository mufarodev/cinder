    @JvmStatic
    fun uri(nameOrUri: String): String {
        if (nameOrUri.startsWith(URI_PREFIX)) return nameOrUri
        if (nameOrUri.startsWith("ic_mana_")) return URI_PREFIX + nameOrUri
        return MANA_PREFIX + nameOrUri
    }

    @JvmStatic
    fun isManaIconUri(uri: String?): Boolean {
        if (uri == null || !uri.startsWith(MANA_PREFIX)) return false
        if (uri.length <= MANA_PREFIX.length) return false
        for (i in MANA_PREFIX.length until uri.length) {
            val c = uri[i]
            val valid = (c in 'a'..'z') || (c in '0'..'9') || c == '_'
            if (!valid) return false
        }
        return true
    }

    @JvmStatic
    fun allVerified(): List<String> = CURATED
